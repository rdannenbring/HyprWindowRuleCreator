"""Persist rules to a file this tool owns.

Rules go into a single generated file, never into hand-edited config. Each rule
is fenced by markers so it can be listed and removed later without reparsing
Lua.

Writes are verified: save -> reload -> ask Hyprland for config errors -> roll
back the file and reload again if it complains. A window rule editor that can
leave you with a broken config is worse than editing by hand.
"""

from __future__ import annotations

import os
import re
import shutil
import time
from dataclasses import dataclass
from pathlib import Path

from . import emit, ipc
from .model import Rule
from .branding import APP_NAME, FENCE_TAG
from .settings import Settings

TEMPLATE_MARK = "from-template:"

BEGIN = f"-- >>> {FENCE_TAG} {{id}}"
END = f"-- <<< {FENCE_TAG} {{id}}"
BEGIN_CONF = f"# >>> {FENCE_TAG} {{id}}"
END_CONF = f"# <<< {FENCE_TAG} {{id}}"

HEADER_LUA = f"""\
-- Generated by {APP_NAME}. Safe to edit by hand, but
-- fenced blocks are managed: anything between the >>> and <<< markers may be
-- rewritten or removed by the tool.
--
-- Loaded automatically if your hyprland.lua globs conf.d/*.lua. The `zz-`
-- prefix makes this file sort last in that glob, so a rule at the bottom of
-- this file is the last one evaluated for any window it matches. Renaming the
-- file gives that away.
"""

HEADER_CONF = f"""\
# Generated by {APP_NAME}. Fenced blocks are managed:
# anything between the >>> and <<< markers may be rewritten or removed.
"""


def _write_backup(path: Path) -> Path:
    stamp = time.strftime("%Y%m%d-%H%M%S")
    backup = path.with_suffix(path.suffix + f".bak.{stamp}")
    n = 1
    while backup.exists():  # more than one write in the same second
        backup = path.with_suffix(path.suffix + f".bak.{stamp}.{n}")
        n += 1
    shutil.copy2(path, backup)
    return backup


def backups_for(path: Path) -> list[Path]:
    """Existing backups of `path`, newest first."""
    found = sorted(path.parent.glob(path.name + ".bak.*"), reverse=True)
    return found


def prune_backups(path: Path, keep: int) -> list[Path]:
    """Delete all but the `keep` newest backups. keep=0 means keep everything."""
    if keep <= 0:
        return []
    removed = []
    for old in backups_for(path)[keep:]:
        try:
            old.unlink()
            removed.append(old)
        except OSError:
            pass
    return removed


def default_config_dir() -> Path:
    xdg = os.environ.get("XDG_CONFIG_HOME") or (Path.home() / ".config")
    return Path(xdg) / "hypr"


@dataclass
class SaveResult:
    path: Path
    rule_id: str
    backup: Path | None
    reloaded: bool
    config_errors: str = ""
    rolled_back: bool = False

    @property
    def ok(self) -> bool:
        return not self.rolled_back and not self.config_errors


class RuleStore:
    def __init__(self, config_dir: Path | None = None, dialect: str | None = None,
                 prefs: Settings | None = None):
        self.prefs = prefs or Settings.load()
        self.config_dir = Path(config_dir or default_config_dir())

        chosen = dialect or (None if self.prefs.dialect == "auto"
                             else self.prefs.dialect)
        self.dialect = chosen or emit.detect_dialect(self.config_dir)

        # The configured filename carries a suffix; honour the dialect when
        # they disagree, so switching dialect does not write Lua into a .conf.
        rel = Path(self.prefs.generated_file)
        suffix = "lua" if self.dialect == "lua" else "conf"
        self.path = self.config_dir / rel.with_suffix(f".{suffix}")
        self._migrate_legacy_name(suffix)

    def _migrate_legacy_name(self, suffix: str) -> None:
        """One-time rename of the pre-`zz-` file.

        Only when the target is the default: if the user has pointed the
        setting somewhere else, moving their old file there would be a
        surprise, not a migration.
        """
        if Path(self.prefs.generated_file).name != "zz-windowrule-generated.lua":
            return
        legacy = self.config_dir / "conf.d" / f"windowrule-generated.{suffix}"
        if legacy.exists() and not self.path.exists():
            self.path.parent.mkdir(parents=True, exist_ok=True)
            legacy.rename(self.path)

    # -- markers ----------------------------------------------------------

    def _fence(self, rule_id: str) -> tuple[str, str]:
        if self.dialect == "lua":
            return BEGIN.format(id=rule_id), END.format(id=rule_id)
        return BEGIN_CONF.format(id=rule_id), END_CONF.format(id=rule_id)

    def _header(self) -> str:
        return HEADER_LUA if self.dialect == "lua" else HEADER_CONF

    @staticmethod
    def new_rule_id() -> str:
        return time.strftime("%Y%m%d-%H%M%S")

    # -- reads ------------------------------------------------------------

    def existing_ids(self) -> list[str]:
        if not self.path.exists():
            return []
        pattern = re.compile(rf"^[-#]+ >>> {re.escape(FENCE_TAG)} (\S+)\s*$", re.M)
        return pattern.findall(self.path.read_text())

    def read_block(self, rule_id: str) -> str | None:
        if not self.path.exists():
            return None
        begin, end = self._fence(rule_id)
        text = self.path.read_text()
        start = text.find(begin)
        stop = text.find(end)
        if start == -1 or stop == -1:
            return None
        return text[start + len(begin):stop].strip("\n")

    # -- writes -----------------------------------------------------------

    def _backup(self) -> Path | None:
        if not self.path.exists():
            return None
        backup = _write_backup(self.path)
        prune_backups(self.path, self.prefs.backup_keep)
        return backup

    def validate(self, body: str) -> str | None:
        """Compile-check some prospective config text. None means it's fine.

        Checks the body in the context of the whole file it would join, so a
        stray unbalanced brace can't pass by looking fine in isolation.
        """
        if self.dialect != "lua":
            return None
        head = self.path.read_text() if self.path.exists() else self._header()
        return ipc.compile_lua(f"{head}\n{body}\n")

    def preview_text(self, rule: Rule, rule_id: str | None = None) -> str:
        rule_id = rule_id or self.new_rule_id()
        begin, end = self._fence(rule_id)
        body = emit.render(rule, self.dialect)
        return f"{begin}\n{body}\n{end}"

    def template_marker(self, template_id: str) -> str:
        """The provenance line written above a rule created from a template.

        A comment rather than anything structural: it survives hand-editing,
        it is ignored by the Lua parser, and blocks written before this existed
        simply have none. Matching a rule to its template by name would break
        the moment either is renamed.
        """
        mark = "--" if self.dialect == "lua" else "#"
        return f"{mark} {TEMPLATE_MARK} {template_id}"

    def save(self, rule: Rule, rule_id: str | None = None,
             verify: bool = True, template_id: str | None = None) -> SaveResult:
        valid, why = rule.is_valid()
        if not valid:
            raise ValueError(why)
        body = emit.render(rule, self.dialect)
        if template_id:
            body = self.template_marker(template_id) + "\n" + body
        return self.save_raw(body, rule_id, verify)

    def save_raw(self, body: str, rule_id: str | None = None,
                 verify: bool = True) -> SaveResult:
        """Append already-rendered config text.

        Used directly when the user has hand-edited the generated output --
        their text goes in verbatim, and the same pre-flight compile guards it.
        """
        body = body.strip("\n")
        if not body:
            raise ValueError("nothing to save")

        rule_id = rule_id or self.new_rule_id()
        self.path.parent.mkdir(parents=True, exist_ok=True)
        original = self.path.read_text() if self.path.exists() else None

        begin, end = self._fence(rule_id)
        text = original if original is not None else self._header()
        if not text.endswith("\n"):
            text += "\n"
        text += f"\n{begin}\n{body}\n{end}\n"

        # Pre-flight. Post-write verification alone is not enough: a .lua file
        # pulled in by a loadfile()-style glob reports its syntax errors on
        # stderr, so `configerrors` stays empty and a broken file would look
        # like a clean save. Compile it before anything touches the disk.
        if verify and self.dialect == "lua":
            error = ipc.compile_lua(text)
            if error:
                return SaveResult(
                    self.path, rule_id, backup=None, reloaded=False,
                    config_errors=error, rolled_back=True,
                )

        backup = self._backup()
        self.path.write_text(text)

        result = SaveResult(self.path, rule_id, backup, reloaded=False)
        if not verify:
            return result

        errors = self._reload_and_check()
        result.reloaded = True
        if errors:
            # Put it back exactly as it was, then reload again so the running
            # compositor matches what is on disk.
            if original is None:
                self.path.unlink(missing_ok=True)
            else:
                self.path.write_text(original)
            self._reload_and_check()
            result.config_errors = errors
            result.rolled_back = True
        return result

    def update_raw(self, rule_id: str, body: str,
                   verify: bool = True) -> SaveResult:
        """Replace an existing fenced block, keeping its position in the file.

        Position matters: rules are evaluated top to bottom, so re-appending an
        edited rule would silently change which one wins.
        """
        body = body.strip("\n")
        if not self.path.exists():
            return self.save_raw(body, rule_id, verify)

        begin, end = self._fence(rule_id)
        original = self.path.read_text()
        start, stop = original.find(begin), original.find(end)
        if start == -1 or stop == -1:
            return self.save_raw(body, rule_id, verify)

        text = (original[:start] + f"{begin}\n{body}\n{end}"
                + original[stop + len(end):])

        if verify and self.dialect == "lua":
            error = ipc.compile_lua(text)
            if error:
                return SaveResult(self.path, rule_id, backup=None, reloaded=False,
                                  config_errors=error, rolled_back=True)

        backup = self._backup()
        self.path.write_text(text)
        result = SaveResult(self.path, rule_id, backup, reloaded=False)
        if not verify:
            return result

        errors = self._reload_and_check()
        result.reloaded = True
        if errors:
            self.path.write_text(original)
            self._reload_and_check()
            result.config_errors = errors
            result.rolled_back = True
        return result

    def update(self, rule_id: str, rule: Rule, verify: bool = True) -> SaveResult:
        valid, why = rule.is_valid()
        if not valid:
            raise ValueError(why)
        return self.update_raw(rule_id, emit.render(rule, self.dialect), verify)

    def _extract_block(self, rule_id: str) -> tuple[str, str, str] | None:
        """(text_without_block, fenced_block, original_text)."""
        if not self.path.exists():
            return None
        begin, end = self._fence(rule_id)
        original = self.path.read_text()
        start, stop = original.find(begin), original.find(end)
        if start == -1 or stop == -1:
            return None
        block = original[start:stop + len(end)]
        without = original[:start].rstrip("\n") + "\n" + \
            original[stop + len(end):].lstrip("\n")
        return without, block, original

    def _commit(self, rule_id: str, text: str, original: str,
                verify: bool) -> SaveResult:
        """Write `text`, verifying and rolling back to `original` if rejected."""
        if verify and self.dialect == "lua":
            error = ipc.compile_lua(text)
            if error:
                return SaveResult(self.path, rule_id, None, False, error, True)
        backup = self._backup()
        self.path.write_text(text)
        result = SaveResult(self.path, rule_id, backup, reloaded=False)
        if not verify:
            return result
        errors = self._reload_and_check()
        result.reloaded = True
        if errors:
            self.path.write_text(original)
            self._reload_and_check()
            result.config_errors = errors
            result.rolled_back = True
        return result

    def move_to_end(self, rule_id: str, verify: bool = True) -> SaveResult:
        """Move a block to the end of the file, giving it the last word.

        Combined with this file sorting last in the conf.d glob, that makes it
        the final rule evaluated for any window it matches.

        No UI calls this: the "Make Active" button it backed was removed for
        being destructive without showing what it would silence. Kept as a
        primitive because reordering is a coherent operation on its own, and
        it is covered by the store tests.
        """
        parts = self._extract_block(rule_id)
        if parts is None:
            raise ValueError(f"no managed rule {rule_id}")
        without, block, original = parts
        text = without.rstrip("\n") + "\n\n" + block + "\n"
        return self._commit(rule_id, text, original, verify)

    def set_enabled(self, rule_id: str, enabled: bool,
                    verify: bool = True) -> SaveResult:
        """Comment a managed rule out, or bring it back."""
        parts = self._extract_block(rule_id)
        if parts is None:
            raise ValueError(f"no managed rule {rule_id}")
        _, block, original = parts
        begin, end = self._fence(rule_id)
        marker = "--" if self.dialect == "lua" else "#"

        body_lines = block.splitlines()[1:-1]  # keep the fences readable
        if enabled:
            new_body = [re.sub(rf"^(\s*){re.escape(marker)} ?", r"\1", ln)
                        for ln in body_lines]
        else:
            new_body = [ln if not ln.strip() else f"{marker} {ln}"
                        for ln in body_lines]

        new_block = "\n".join([begin, *new_body, end])
        return self._commit(rule_id, original.replace(block, new_block),
                            original, verify)

    def duplicate(self, rule_id: str, verify: bool = True) -> SaveResult:
        """Copy a rule to the end of the file under a fresh id."""
        parts = self._extract_block(rule_id)
        if parts is None:
            raise ValueError(f"no managed rule {rule_id}")
        _, block, original = parts
        begin, end = self._fence(rule_id)
        body = block[len(begin):-len(end)].strip("\n")

        new_id = self.new_rule_id()
        if new_id == rule_id:
            new_id += "-copy"
        nbegin, nend = self._fence(new_id)
        text = original.rstrip("\n") + f"\n\n{nbegin}\n{body}\n{nend}\n"
        return self._commit(new_id, text, original, verify)

    def remove(self, rule_id: str, verify: bool = True) -> bool:
        if not self.path.exists():
            return False
        begin, end = self._fence(rule_id)
        text = self.path.read_text()
        start = text.find(begin)
        stop = text.find(end)
        if start == -1 or stop == -1:
            return False
        self._backup()
        cut = text[:start].rstrip("\n") + "\n" + text[stop + len(end):].lstrip("\n")
        self.path.write_text(cut)
        if verify:
            self._reload_and_check()
        return True

    # -- foreign files ----------------------------------------------------

    @staticmethod
    def toggle_foreign(path: Path, site, enable: bool,
                       verify: bool = True, keep: int = 10) -> SaveResult:
        """Comment out (or restore) one rule in a file this tool did not write.

        Deliberately the only write we make to foreign config, and never a
        delete: commenting is reversible and obvious in a diff, so a wrong
        guess about which rule to touch stays recoverable. The file is backed
        up first and restored if Hyprland rejects the result.
        """
        original = path.read_text()
        chunk = original[site.start:site.end]
        marker = "--" if path.suffix == ".lua" else "#"

        if enable:
            new_chunk = "\n".join(
                re.sub(rf"^(\s*){re.escape(marker)} ?", r"\1", ln)
                for ln in chunk.splitlines())
        else:
            new_chunk = "\n".join(
                ln if not ln.strip() else f"{marker} {ln}"
                for ln in chunk.splitlines())

        text = original[:site.start] + new_chunk + original[site.end:]
        result = SaveResult(path, "foreign", None, reloaded=False)

        if verify and path.suffix == ".lua":
            error = ipc.compile_lua(text)
            if error:
                result.config_errors = error
                result.rolled_back = True
                return result

        result.backup = _write_backup(path)
        prune_backups(path, keep)
        path.write_text(text)

        if verify:
            errors = RuleStore._reload_and_check()
            result.reloaded = True
            if errors:
                path.write_text(original)
                RuleStore._reload_and_check()
                result.config_errors = errors
                result.rolled_back = True
        return result

    # -- verification -----------------------------------------------------

    @staticmethod
    def _reload_and_check() -> str:
        ipc.reload()
        time.sleep(0.25)  # the parse happens asynchronously
        try:
            raw = ipc.request_json("configerrors")
        except ipc.HyprError:
            return ""
        if isinstance(raw, list):
            joined = "\n".join(s for s in raw if isinstance(s, str) and s.strip())
            return joined.strip()
        return str(raw).strip() if raw else ""
